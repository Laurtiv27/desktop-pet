#!/usr/bin/env node
/**
 * 把共享层打成桌面 Helper 的经典 script。
 *
 * 必须是经典 script 而非 ESM：桌面 Helper 从 file:// 载入页面，Chromium 对 file:// 的 ES module 有 CORS 限制。
 * - src/shared/index.ts → runtime/electron-helper/shared-core.js，全局 window.PetShared
 * - src/shared/posture/browser-entry.ts → runtime/electron-helper/posture/core.js，全局 window.PostureCore
 *   只含阈值、指标和引擎。config 的磁盘读写、演出、告警、在离不进页面包。
 * 只产这两份构建产物，不做类型检查、不写声明；由发布链的 npm run build:desktop-core 调用。
 * @module dsh-pet/scripts/build-desktop-core
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { rolldown } from 'rolldown';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));

/**
 * @param {string} input 入口绝对路径
 * @param {string} out 产物绝对路径
 * @param {string} name IIFE 全局名
 * @param {string} sourceLabel 文件头里写的源文件（相对仓库根）
 * @param {string} logLabel 成功日志
 */
async function buildIife(input, out, name, sourceLabel, logLabel) {
  mkdirSync(dirname(out), { recursive: true });
  const bundle = await rolldown({
    input,
    platform: 'browser',
  });
  await bundle.write({
    format: 'iife',
    name,
    file: out,
  });
  // 产物提交进仓库且由 Helper 从 file:// 加载：文件头必须声明生成来源，避免被手改后又被构建无声覆盖。
  const banner = [
    '/**',
    ' * @generated by `npm run build:desktop-core`（scripts/build-desktop-core.mjs），请勿手改。',
    ` * 源文件：${sourceLabel}。`,
    ' */',
  ].join('\n');
  const code = readFileSync(out, 'utf8');
  if (!code.startsWith('/**')) writeFileSync(out, banner + '\n' + code);
  console.log(logLabel);
}

try {
  await buildIife(
    join(ROOT, 'src', 'shared', 'index.ts'),
    join(ROOT, 'runtime', 'electron-helper', 'shared-core.js'),
    'PetShared',
    'src/shared/index.ts',
    '[build-desktop-core] ✓ runtime/electron-helper/shared-core.js (window.PetShared)',
  );
  await buildIife(
    join(ROOT, 'src', 'shared', 'posture', 'browser-entry.ts'),
    join(ROOT, 'runtime', 'electron-helper', 'posture', 'core.js'),
    'PostureCore',
    'src/shared/posture/browser-entry.ts',
    '[build-desktop-core] ✓ runtime/electron-helper/posture/core.js (window.PostureCore)',
  );
} catch (error) {
  console.error('[build-desktop-core] build failed:', error);
  process.exit(1);
}

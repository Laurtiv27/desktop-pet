#!/usr/bin/env node
/**
 * 把 three + GLTFLoader 打成桌面 Helper 的经典 script。
 *
 * file:// 页面不能用 ESM，所以产出 IIFE。rolldown 1.0.0-beta.7 的 output.name 只接受 string，
 * 不能传 false；这里省略 name，避免再挂一个总对象。命名空间导入会被改写，
 * 闭包末尾必须从 exports 挂到 globalThis，页面里即 window.THREE / window.GLTFLoader。
 * 由 npm run vendor:three-model3d 调用；prepare.js 在 build:desktop-core 之后再跑一次，保证发布物齐全。
 * @module dsh-pet/scripts/vendor-three-model3d
 */
import { mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { runInNewContext } from 'node:vm';
import { rolldown } from 'rolldown';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const ENTRY = join(ROOT, 'scripts', 'vendor', 'model3d-three-entry.mjs');
const OUT = join(ROOT, 'runtime', 'electron-helper', 'vendor', 'three-gltf.iife.js');

const BANNER = [
  '/**',
  ' * @generated by `npm run vendor:three-model3d`（scripts/vendor-three-model3d.mjs），请勿手改。',
  ' * 源文件：scripts/vendor/model3d-three-entry.mjs。',
  ' * 挂载：window.THREE、window.GLTFLoader。',
  ' */',
].join('\n');

/**
 * 打包 three + GLTFLoader，并确认产物非空且挂上了两个全局。
 *
 * @returns {Promise<{ bytes: number }>}
 */
export async function vendorThreeModel3d() {
  mkdirSync(dirname(OUT), { recursive: true });
  const bundle = await rolldown({
    input: ENTRY,
    platform: 'browser',
  });
  try {
    await bundle.write({
      format: 'iife',
      // 省略 name（本版 rolldown 拒绝 name: false）：不把导出对象赋给额外全局。
      // outro 是原文拼接，不会跟着命名空间导入改写；exports 是 IIFE 形参，挂载后才不会 ReferenceError。
      file: OUT,
      inlineDynamicImports: true,
      outro: ['globalThis.THREE = exports.THREE;', 'globalThis.GLTFLoader = exports.GLTFLoader;'].join('\n'),
    });
  } finally {
    await bundle.close();
  }

  const code = readFileSync(OUT, 'utf8');
  if (!code.startsWith('/**')) writeFileSync(OUT, `${BANNER}\n${code}`);
  const bytes = statSync(OUT).size;
  const finalCode = readFileSync(OUT, 'utf8');
  if (bytes < 1) throw new Error('[vendor-three-model3d] 产物为空');
  if (
    !finalCode.includes('globalThis.THREE = exports.THREE;') ||
    !finalCode.includes('globalThis.GLTFLoader = exports.GLTFLoader;')
  ) {
    throw new Error('[vendor-three-model3d] 产物未挂上 window.THREE / window.GLTFLoader');
  }
  const sandbox = {};
  runInNewContext(finalCode, sandbox, { filename: OUT });
  if (typeof sandbox.THREE?.WebGLRenderer !== 'function' || typeof sandbox.GLTFLoader !== 'function') {
    throw new Error('[vendor-three-model3d] 产物执行后缺少 THREE.WebGLRenderer 或 GLTFLoader');
  }
  console.log(`[vendor-three-model3d] ✓ runtime/electron-helper/vendor/three-gltf.iife.js (${bytes} bytes)`);
  return { bytes };
}

const invoked = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invoked) {
  vendorThreeModel3d().catch((error) => {
    console.error('[vendor-three-model3d] build failed:', error);
    process.exit(1);
  });
}
